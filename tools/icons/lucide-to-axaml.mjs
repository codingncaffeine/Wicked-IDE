// Turns Lucide SVG icons (24x24 stroke icons, ISC licence) into one Avalonia resource dictionary of StreamGeometry,
// keyed Icon.<name>. Circles, ellipses, rects, lines and polylines become path figures; the stroke itself is drawn by
// the app's Icon control, so the dictionary holds outlines only.
//   node tools/icons/lucide-to-axaml.mjs <svg folder> <out.axaml>
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, basename } from 'node:path';

const [dir, out] = process.argv.slice(2);
if (!dir || !out) { console.error('usage: lucide-to-axaml.mjs <svg folder> <out.axaml>'); process.exit(2); }

const attrs = (tag) => Object.fromEntries([...tag.matchAll(/([a-z0-9-]+)="([^"]*)"/g)].map(m => [m[1], m[2]]));
const n = (v) => Number(v ?? 0);

// A path's first 'm' is absolute in SVG, and the pairs after it are relative linetos ("m7 16.5-4.74-2.85").
// Joined after another figure it would turn relative, so it becomes 'M x y' and the pairs after it an explicit 'l'.
const num = String.raw`-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?`;
const firstMove = new RegExp(String.raw`^\s*m\s*(${num})[\s,]*(${num})\s*,?`);
function absoluteStart(d) {
  const m = d.match(firstMove);
  if (!m) return d;
  const rest = d.slice(m[0].length);
  return `M${m[1]} ${m[2]}` + (/^[-.\d]/.test(rest) ? 'l' : '') + rest;
}

function figures(svg) {
  const parts = [];
  for (const m of svg.matchAll(/<(path|circle|ellipse|rect|line|polyline|polygon)\b([^>]*)\/?>/g)) {
    const [, kind, rest] = m;
    const a = attrs(rest);
    switch (kind) {
      case 'path': parts.push(absoluteStart(a.d)); break;
      case 'circle': case 'ellipse': {
        const cx = n(a.cx), cy = n(a.cy), rx = n(a.rx ?? a.r), ry = n(a.ry ?? a.r);
        parts.push(`M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0z`);
        break;
      }
      case 'rect': {
        const x = n(a.x), y = n(a.y), w = n(a.width), h = n(a.height), r = Math.min(n(a.rx ?? a.ry), w / 2, h / 2);
        parts.push(r > 0
          ? `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}z`
          : `M${x} ${y}h${w}v${h}h${-w}z`);
        break;
      }
      case 'line': parts.push(`M${n(a.x1)} ${n(a.y1)}L${n(a.x2)} ${n(a.y2)}`); break;
      case 'polyline': case 'polygon': {
        const p = a.points.trim().split(/[\s,]+/).map(Number);
        let d = `M${p[0]} ${p[1]}`;
        for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`;
        parts.push(kind === 'polygon' ? d + 'z' : d);
        break;
      }
    }
  }
  return parts.join(' ');
}

const names = readdirSync(dir).filter(f => f.endsWith('.svg')).sort();
const pascal = (s) => s.split('-').map(w => w[0].toUpperCase() + w.slice(1)).join('');
let xml = `<!-- Generated by tools/icons/lucide-to-axaml.mjs from Lucide (ISC licence, see THIRD-PARTY-NOTICES.md). Do not edit. -->
<ResourceDictionary xmlns="https://github.com/avaloniaui"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
`;
for (const f of names) {
  const d = figures(readFileSync(join(dir, f), 'utf8'));
  xml += `  <StreamGeometry x:Key="Icon.${pascal(basename(f, '.svg'))}">${d}</StreamGeometry>\n`;
}
xml += '</ResourceDictionary>\n';
writeFileSync(out, xml);
console.log(`${names.length} icons -> ${out}`);
