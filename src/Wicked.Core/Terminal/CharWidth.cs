    public static int Of(int rune)
    {
        if (rune < 0x300) return 1;
        if (rune == 0xAD) return 1;
        if (InTable(Wide, rune)) return 2;
        if (rune < 0x10000 && rune is >= 0xD800 and <= 0xDFFF) return 1;
        return IsZeroWidth(rune) ? 0 : 1;
    }

    /// <summary>Marks, joiners and variation selectors: drawn on the character before.</summary>
    public static bool IsZeroWidth(int rune)
    {
        if (rune < 0x300) return false;
        if (rune is >= 0x1F3FB and <= 0x1F3FF) return false;
        var category = CharUnicodeInfo.GetUnicodeCategory(rune);
        return category is UnicodeCategory.NonSpacingMark or UnicodeCategory.EnclosingMark or UnicodeCategory.Format
            || rune is >= 0x1160 and <= 0x11FF;
    }

    /// <summary>A base character that, followed by U+FE0F, is drawn as a two-cell emoji.</summary>
    public static bool WidensWithVariationSelector(int rune) => InTable(TextEmoji, rune);

    public static bool IsEmojiModifier(int rune) => rune is >= 0x1F3FB and <= 0x1F3FF;

    public static bool IsRegionalIndicator(int rune) => rune is >= 0x1F1E6 and <= 0x1F1FF;

    private static bool InTable((int From, int To)[] table, int rune)
    {
        int lo = 0, hi = table.Length - 1;
        while (lo <= hi)
        {
            var mid = (lo + hi) >> 1;
            var (from, to) = table[mid];
            if (rune < from) hi = mid - 1;
            else if (rune > to) lo = mid + 1;
            else return true;
        }

        return false;
    }
